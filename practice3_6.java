public class practice3_6 {
    public static void main(String[] args) {
        int i = 100;
        byte b = (byte) i;
        System.out.println(b); 

        double d = 15.9;
        int x = (int) d;
        System.out.println(x); 

        long l = 5000L;
        short s = (short) l;
        System.out.println(s); 

        int code = 65;
        char c = (char) code;
        System.out.println(c); 

        int num = 130;
        byte small = (byte) num;
        System.out.println(small); 
    }
}
