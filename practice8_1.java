public class practice8_1 {
    public static void main(String[] args) {
        // Бесконечный цикл while
        while (true) {
            System.out.println("Бесконечный цикл while");
        }

        // Бесконечный цикл do-while
        do {
            System.out.println("Бесконечный цикл do-while");
        } while (true);
    }
}